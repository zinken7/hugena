import { test, expect } from '@playwright/test';
test('customer compares opinions, chooses an adviser, then records and retains a scoped review', async ({ page }) => {
  const errors: string[]=[]; page.on('pageerror', e=>errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:/AI sounds certain/})).toBeVisible();
  await page.screenshot({path:'artifacts/home-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Verify an AI claim'}).click();
  await page.getByRole('button',{name:'Use the example'}).click();
  await page.getByRole('button',{name:'Compare advisers',exact:true}).click();
  await expect(page.getByText('SAMPLE OPINION / HOSTING-COST EXAMPLE').first()).toBeVisible();
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  await page.screenshot({path:'artifacts/advisers-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'External advisers',exact:true}).click();
  await page.getByRole('button',{name:'+ Add external adviser'}).click();
  await page.getByLabel('Adviser name').fill('Test Adviser');
  await page.getByLabel('Expertise (separated by commas)').fill('Cloud costs, Architecture');
  await page.getByLabel('About this adviser').fill('Independent specialist in cloud cost modelling.');
  await page.getByLabel('Sample opinion on the hosting-cost example').fill('I would establish requests per session and storage growth before checking the cost estimate.');
  await page.getByRole('checkbox').check();
  await page.getByRole('button',{name:'Add demo profile',exact:true}).click();
  const card=page.getByRole('article').filter({has:page.getByRole('heading',{name:'Test Adviser',exact:true})});
  await expect(card.getByText(/requests per session/)).toBeVisible();
  await card.getByRole('button',{name:'Choose adviser'}).click();
  await expect(page.getByRole('heading',{name:'Know what you’re getting.'})).toBeVisible();
  await page.getByRole('button',{name:'Create demo request'}).click();
  await expect(page.getByText('AWAITING REVIEW · DEMO')).toBeVisible();
  await page.getByLabel('Key finding').fill('The estimate lacks request-volume assumptions.');
  await page.getByLabel('Evidence and sources').fill('The supplied context does not state requests per user or bandwidth.');
  await page.getByLabel('Recommended next step').fill('Model low and high usage scenarios before selecting the paid plan.');
  await page.getByRole('button',{name:'Save assessment & view report'}).click();
  await expect(page.getByText('The estimate lacks request-volume assumptions.')).toBeVisible();
  await page.getByRole('button',{name:'Back to adviser desk'}).click();
  await page.getByLabel('Demo case status').selectOption('paid');
  await expect(page.getByText('A$20.00', {exact:true})).toBeVisible();
  await page.reload();
  await page.getByRole('button',{name:'My review',exact:true}).click();
  await expect(page.getByLabel('Key finding')).toHaveValue('The estimate lacks request-volume assumptions.');
  await expect(page.getByLabel('Demo case status')).toHaveValue('paid');
  expect(errors).toEqual([]);
});
test('mobile sample and claim flow have no horizontal overflow',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  await page.screenshot({path:'artifacts/home-mobile.png',fullPage:true});
  const overflow=()=>page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
  expect(await overflow()).toBe(false);
  await page.getByRole('button',{name:'See a sample review'}).click();
  await expect(page.getByText('Insufficient evidence',{exact:true})).toBeVisible();
  expect(await overflow()).toBe(false);
  await page.getByRole('button',{name:'Check another claim'}).click();
  await page.getByRole('button',{name:'Use the example'}).click();
  await page.getByRole('button',{name:'Compare advisers',exact:true}).click();
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  await page.screenshot({path:'artifacts/advisers-mobile.png',fullPage:true});
  expect(await overflow()).toBe(false);
});
